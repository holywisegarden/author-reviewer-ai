export function parseCsvToReviewers(csvContent: string): ReviewerOutlet[] {
  const lines = csvContent.split('\n').filter((l) => l.trim().length > 0);
  if (lines.length < 2) return [];

  const reviewers: ReviewerOutlet[] = [];
  // Skip header line
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    // Regex for CSV parsing handling quotes
    const regex = /(?:^|,)(?:"([^"]*(?:""[^"]*)*)"|([^,]*))/g;
    const fields: string[] = [];
    let match;
    while ((match = regex.exec(line))) {
      let val = match[1] !== undefined ? match[1].replace(/""/g, '"') : match[2];
      fields.push(val ? val.trim() : '');
      if (regex.lastIndex >= line.length) break;
    }

    if (fields.length >= 2 && fields[0]) {
      const pubName = fields[0];
      const website = fields[1] || '';
      const email = fields[2] || '';
      const genresRaw = fields[3] || 'All Genres';
      const acceptsIndies = fields[4] || 'Yes';
      const contactMethod = fields[5] || 'Website / submission policy';
      const cost = fields[6] || 'Verify current policy';
      const platformsRaw = fields[7] || 'Website; Blog';
      const subReqs = fields[8] || 'Check reviewer guidelines';
      const fitJack = (fields[9] as any) || 'Potential';
      const fitEchoes = (fields[10] as any) || 'Potential';
      const source = fields[11] || 'Imported Reviewer Directory';
      const lastVerified = fields[12] || new Date().toISOString().split('T')[0];

      const slug = pubName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

      reviewers.push({
        id: `rev-import-${slug}-${Date.now()}-${i}`,
        name: `${pubName} Team`,
        publication: pubName,
        category: 'indie_blog',
        email: email || undefined,
        website: website || 'https://google.com',
        submissionUrl: website || 'https://google.com',
        leadTimeNotice: 'Standard 3-4 weeks lead time recommended.',
        leadTimeDays: 21,
        costPolicy: cost,
        preferredGenres: genresRaw.split(';').map((g) => g.trim()).filter(Boolean),
        formatsAccepted: ['ePub', 'PDF', 'Kindle'],
        guidelines: `${subReqs}. Accepts indie: ${acceptsIndies}. Contact: ${contactMethod}.`,
        proTips: ['Personalize your greeting and mention specific books they reviewed.'],
        typicalResponseRate: 30,
        avgTurnaroundDays: 25,
        followerOrReaderReach: platformsRaw,
        requiresFTCCompliance: true,
        isPreloaded: false,
        acceptsIndies,
        contactMethod,
        reviewPlatforms: platformsRaw.split(';').map((p) => p.trim()).filter(Boolean),
        submissionRequirements: subReqs,
        source,
        lastVerified,
        bookFitScores: {
          jackAndBlaze: fitJack,
          echoesOfTheHeart: fitEchoes,
        },
      });
    }
  }

  return reviewers;
}

export function exportReviewersToCsv(reviewers: ReviewerOutlet[]): string {
  const header = [
    'Reviewer / Site',
    'Website',
    'Public Email',
    'Genres / What They Look For',
    'Accepts Indie / Self-Published',
    'Contact Method',
    'Cost',
    'Review Platforms',
    'Submission Requirements',
    'Jack and Blaze Fit',
    'Echoes of the Heart Fit',
    'Source',
    'Last Verified',
  ].join(',');

  const rows = reviewers.map((r) => {
    const escapeCsv = (str?: string) => {
      if (!str) return '""';
      if (str.includes(',') || str.includes('"') || str.includes('\n')) {
        return `"${str.replace(/"/g, '""')}"`;
      }
      return `"${str}"`;
    };

    return [
      escapeCsv(r.publication),
      escapeCsv(r.website),
      escapeCsv(r.email || ''),
      escapeCsv(r.preferredGenres.join('; ')),
      escapeCsv(r.acceptsIndies || 'Yes'),
      escapeCsv(r.contactMethod || 'Website / submission policy'),
      escapeCsv(r.costPolicy || 'Free Editorial Review'),
      escapeCsv(r.reviewPlatforms?.join('; ') || r.followerOrReaderReach || 'Blog'),
      escapeCsv(r.submissionRequirements || r.guidelines),
      escapeCsv(r.bookFitScores?.jackAndBlaze || 'Potential'),
      escapeCsv(r.bookFitScores?.echoesOfTheHeart || 'Potential'),
      escapeCsv(r.source || 'Indies Today 2026 reviewer directory'),
      escapeCsv(r.lastVerified || '2026-10-04'),
    ].join(',');
  });

  return [header, ...rows].join('\n');
}
